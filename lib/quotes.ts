function hash(s: string) {
  let h = 2166136261
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619)
  return h >>> 0
}

/** Күннің сөзі: күн сайын ауысады, әр оқушыда әртүрлі */
export function quoteIndexFor(day: string, seed = '') {
  return hash(`${day}|${seed}`) % QUOTES.length
}
